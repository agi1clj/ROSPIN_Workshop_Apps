"""Rospin NDVI API.

    GET /health                              liveness information used by Azure and CI/CD
    GET /api/regions                         study regions
    GET /api/regions/{id}/ndvi?source=...    NDVI time series (sample = default, live = Sentinel-2)
    GET /docs                                OpenAPI documentation generated by FastAPI
"""

from datetime import datetime, timezone
from typing import Annotated, Literal

from fastapi import FastAPI, HTTPException, Path, Query
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware

from . import ndvi
from .config import get_settings
from .models import Health, NdviSeries, Region
from .regions import REGIONS, REGIONS_BY_ID

settings = get_settings()

app = FastAPI(
    title="Rospin NDVI API",
    version=settings.app_version,
    description="Vegetation health (NDVI) of Romanian regions from Sentinel-2 satellite data.",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_methods=["GET"],
    allow_headers=["*"],
)


@app.get("/", include_in_schema=False)
def root() -> dict[str, str]:
    return {"service": settings.app_name, "docs": "/docs", "regions": "/api/regions"}


@app.get("/health", response_model=Health, tags=["health"])
def health() -> Health:
    return Health(
        status="ok",
        service=settings.app_name,
        version=settings.app_version,
        timestamp=datetime.now(timezone.utc),
    )


@app.get("/api/regions", response_model=list[Region], tags=["data"])
def list_regions() -> list[Region]:
    return REGIONS


@app.get("/api/regions/{region_id}/ndvi", response_model=NdviSeries, tags=["data"])
async def region_ndvi(
    region_id: Annotated[str, Path(pattern=r"^[a-z0-9-]{3,40}$", description="Region id, e.g. cluj-farmland")],
    source: Annotated[Literal["sample", "live"], Query(description="sample = precomputed, live = Sentinel-2")] = "sample",
) -> NdviSeries:
    region = REGIONS_BY_ID.get(region_id)
    if region is None:
        raise HTTPException(status_code=404, detail=f"Region '{region_id}' not found")
    if source == "sample":
        series = ndvi.sample_series(region)
        if series is None:
            raise HTTPException(status_code=404, detail="No sample data for this region")
        return series
    try:
        return await run_in_threadpool(ndvi.live_series, region)
    except Exception as error:  # upstream catalogue or archive unavailable
        raise HTTPException(status_code=502, detail=f"Live Sentinel-2 data unavailable: {error}") from error
